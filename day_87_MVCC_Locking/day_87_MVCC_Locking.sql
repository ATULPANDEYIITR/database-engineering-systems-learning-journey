-- ------------------------------------------------------------
-- 17. ARCHITECTURAL NOTES
-- ------------------------------------------------------------

-- PostgreSQL MVCC:
-- Readers generally do not block writers.
-- Writers generally do not block ordinary snapshot readers.
-- UPDATE and DELETE create new row versions.
-- Old row versions may remain until vacuum can reclaim them.
--
-- Pessimistic locking:
-- SELECT FOR UPDATE prevents competing transactions from
-- acquiring conflicting row locks until transaction completion.
--
-- Optimistic concurrency:
-- A version predicate detects stale application state.
-- It does not eliminate database-level write locks.
--
-- Important operational concerns:
-- 1. Long transactions delay cleanup of obsolete row versions.
-- 2. Deadlocks can occur when transactions lock rows differently.
-- 3. Consistent lock ordering reduces deadlock risk.
-- 4. SERIALIZABLE transactions may require retry handling.
-- 5. Vacuum and transaction age require monitoring.
-- 6. Lock timeout and statement timeout should be configured.
-- 7. Retry logic must distinguish transient conflicts from
--    permanent business validation failures.
--
-- This script intentionally does not disable PostgreSQL's
-- internal MVCC behavior or claim that SELECT FOR UPDATE
-- replaces the database's version-based visibility system.
