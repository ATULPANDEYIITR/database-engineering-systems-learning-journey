-- ------------------------------------------------------------
-- 13. REPORTING VIEWS
-- ------------------------------------------------------------

CREATE OR REPLACE VIEW inventory_concurrency_report AS
SELECT
    i.inventory_id,
    i.product_code,
    i.product_name,
    i.available_quantity,
    i.version_number,
    i.updated_at,
    COUNT(a.audit_id) AS modification_count,
    MAX(a.execution_time) AS last_modification
FROM inventory i
LEFT JOIN transaction_audit a
    ON a.inventory_id = i.inventory_id
GROUP BY
    i.inventory_id,
    i.product_code,
    i.product_name,
    i.available_quantity,
    i.version_number,
    i.updated_at;


CREATE OR REPLACE VIEW concurrency_event_report AS
SELECT
    event_type,
    COUNT(*) AS event_count,
    MIN(recorded_at) AS first_occurrence,
    MAX(recorded_at) AS last_occurrence
FROM concurrency_events
GROUP BY event_type;


-- ------------------------------------------------------------
-- 14. AGGREGATION AND EVALUATION QUERIES
-- ------------------------------------------------------------

-- Current inventory state.
SELECT *
FROM inventory_concurrency_report
ORDER BY product_code;


-- Audit activity by product.
SELECT
    i.product_code,
    COUNT(a.audit_id) AS total_updates,
    SUM(
        COALESCE(a.old_quantity, 0) -
        COALESCE(a.new_quantity, 0)
    ) AS net_quantity_reduction
FROM inventory i
LEFT JOIN transaction_audit a
    ON a.inventory_id = i.inventory_id
GROUP BY i.product_code
ORDER BY total_updates DESC;


-- Concurrency event distribution.
SELECT *
FROM concurrency_event_report
ORDER BY event_count DESC;


-- Optimistic conflicts.
SELECT
    event_type,
    COUNT(*) AS conflict_count
FROM concurrency_events
WHERE event_type = 'OPTIMISTIC_CONFLICT'
GROUP BY event_type;


-- Inventory integrity validation.
SELECT
    product_code,
    available_quantity,
    version_number,
    CASE
        WHEN available_quantity < 0 THEN 'INVALID_QUANTITY'
        WHEN version_number <= 0 THEN 'INVALID_VERSION'
        ELSE 'VALID'
    END AS integrity_status
FROM inventory;


-- ------------------------------------------------------------
-- 15. CTE-BASED ARCHITECTURAL WORKLOAD EVALUATION
-- ------------------------------------------------------------

WITH workload AS (
    SELECT
        'Read-heavy reporting'::TEXT AS workload_name,
        0.95::NUMERIC AS read_ratio,
        0.10::NUMERIC AS contention,
        0.05::NUMERIC AS write_hotspot,
        100::NUMERIC AS duration_ms

    UNION ALL

    SELECT
        'High-contention inventory',
        0.30,
        0.90,
        0.90,
        500

    UNION ALL

    SELECT
        'Long-running business transactions',
        0.60,
        0.70,
        0.50,
        5000
),
scores AS (
    SELECT
        workload_name,

        (
            60 * read_ratio
            + 25 * (1 - contention)
            + 15 * (1 - write_hotspot)
            - LEAST(duration_ms / 1000, 20)
        ) AS mvcc_score,

        (
            50 * contention
            + 30 * write_hotspot
            + 20 * LEAST(duration_ms / 1000, 1)
        ) AS locking_score

    FROM workload
)
SELECT
    workload_name,
    ROUND(mvcc_score, 2) AS mvcc_score,
    ROUND(locking_score, 2) AS locking_score,
    CASE
        WHEN mvcc_score >= locking_score THEN 'MVCC'
        ELSE 'PESSIMISTIC_LOCKING'
    END AS preferred_model
FROM scores
ORDER BY workload_name;


