-- ============================================================
-- MVCC VS LOCKING: POSTGRESQL CONCURRENCY LABORATORY
-- PostgreSQL 15+
--
-- Demonstrates:
-- 1. PostgreSQL MVCC architecture.
-- 2. Row-level pessimistic locking.
-- 3. Optimistic version-column validation.
-- 4. Transaction isolation.
-- 5. Concurrent inventory reservations.
-- 6. Deadlock prevention through ordered locking.
-- 7. Transaction auditing.
-- 8. Concurrency metrics and reporting.
-- 9. Architectural workload evaluation.
--
-- Important:
-- PostgreSQL uses MVCC internally. SELECT FOR UPDATE adds
-- explicit row-locking behavior; it does not replace MVCC.
