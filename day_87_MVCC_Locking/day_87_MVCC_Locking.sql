-- Pessimistic reservation.
BEGIN;

SELECT reserve_inventory_locked(
    'LAPTOP-001',
    2
) AS reservation_success;

COMMIT;


-- Optimistic reservation.
-- The version must be read from the current inventory record.

SELECT
    inventory_id,
    available_quantity,
    version_number
FROM inventory
WHERE product_code = 'SERVER-001';

-- Execute with the returned inventory_id and version_number.
-- Example values below are illustrative initial-state values.
-- If the version differs, the operation safely returns FALSE.

SELECT reserve_inventory_optimistic(
    (
        SELECT inventory_id
        FROM inventory
        WHERE product_code = 'SERVER-001'
    ),
    (
        SELECT version_number
        FROM inventory
        WHERE product_code = 'SERVER-001'
    ),
    1
) AS optimistic_reservation_success;


