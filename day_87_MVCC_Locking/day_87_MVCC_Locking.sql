-- ------------------------------------------------------------
-- 3. AUTOMATIC TIMESTAMP MAINTENANCE
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION update_inventory_timestamp()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;


DROP TRIGGER IF EXISTS trg_inventory_timestamp
    ON inventory;

CREATE TRIGGER trg_inventory_timestamp
BEFORE UPDATE ON inventory
FOR EACH ROW
EXECUTE FUNCTION update_inventory_timestamp();


-- ------------------------------------------------------------
-- 4. TRANSACTION AUDIT TRIGGER
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION audit_inventory_changes()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO transaction_audit (
        inventory_id,
        operation,
        old_quantity,
        new_quantity,
        old_version,
        new_version,
        details
    )
    VALUES (
        NEW.inventory_id,
        TG_OP,
        OLD.available_quantity,
        NEW.available_quantity,
        OLD.version_number,
        NEW.version_number,
        jsonb_build_object(
            'database_operation', TG_OP,
            'product_code', NEW.product_code
        )
    );

    RETURN NEW;
END;
$$;


DROP TRIGGER IF EXISTS trg_inventory_audit
    ON inventory;

CREATE TRIGGER trg_inventory_audit
AFTER UPDATE ON inventory
FOR EACH ROW
WHEN (
    OLD.available_quantity IS DISTINCT FROM
        NEW.available_quantity
    OR OLD.version_number IS DISTINCT FROM
        NEW.version_number
)
EXECUTE FUNCTION audit_inventory_changes();


