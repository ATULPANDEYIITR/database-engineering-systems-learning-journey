CREATE SCHEMA IF NOT EXISTS concurrency_lab;

SET search_path TO concurrency_lab, public;

-- ------------------------------------------------------------
-- 1. DOMAIN TABLES
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS inventory (
    inventory_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    product_code VARCHAR(40) NOT NULL UNIQUE,

    product_name VARCHAR(150) NOT NULL,

    available_quantity INTEGER NOT NULL
        CHECK (available_quantity >= 0),

    version_number BIGINT NOT NULL DEFAULT 1
        CHECK (version_number > 0),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    transaction_reference UUID NOT NULL UNIQUE,

    transaction_type VARCHAR(30) NOT NULL
        CHECK (
            transaction_type IN (
                'MVCC_UPDATE',
                'LOCKED_UPDATE',
                'OPTIMISTIC_UPDATE'
            )
        ),

    transaction_status VARCHAR(20) NOT NULL
        CHECK (
            transaction_status IN (
                'STARTED',
                'COMMITTED',
                'ABORTED',
                'REJECTED'
            )
        ),

    description TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    completed_at TIMESTAMPTZ
);


CREATE TABLE IF NOT EXISTS transaction_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    transaction_id BIGINT
        REFERENCES transactions(transaction_id),

    inventory_id BIGINT
        REFERENCES inventory(inventory_id),

    operation VARCHAR(30) NOT NULL,

    old_quantity INTEGER,

    new_quantity INTEGER,

    old_version BIGINT,

    new_version BIGINT,

    execution_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    details JSONB NOT NULL DEFAULT '{}'::JSONB
);


CREATE TABLE IF NOT EXISTS concurrency_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    transaction_reference UUID NOT NULL,

    event_type VARCHAR(40) NOT NULL,

    event_details JSONB NOT NULL DEFAULT '{}'::JSONB,

    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


