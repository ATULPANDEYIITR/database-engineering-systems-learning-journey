-- ------------------------------------------------------------
-- 6. MVCC: SNAPSHOT-BASED READS
-- ------------------------------------------------------------

-- Run in Session A:
--
-- BEGIN ISOLATION LEVEL REPEATABLE READ;
--
-- SELECT
--     inventory_id,
--     product_code,
--     available_quantity,
--     version_number
-- FROM inventory
-- WHERE product_code = 'LAPTOP-001';
--
-- Run in Session B:
--
-- BEGIN;
--
-- UPDATE inventory
-- SET available_quantity = available_quantity - 5,
--     version_number = version_number + 1
-- WHERE product_code = 'LAPTOP-001';
--
-- COMMIT;
--
-- Run again in Session A:
--
-- SELECT available_quantity
-- FROM inventory
-- WHERE product_code = 'LAPTOP-001';
--
-- Under REPEATABLE READ, Session A continues to see
-- its transaction snapshot.
--
-- COMMIT;
--
-- A new transaction sees the newly committed version.
--
-- Under READ COMMITTED, each statement generally obtains
-- a fresh snapshot instead.


-- ------------------------------------------------------------
-- 7. PESSIMISTIC LOCKING FUNCTION
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION reserve_inventory_locked(
    p_product_code VARCHAR(40),
    p_quantity INTEGER
)
RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
DECLARE
    v_inventory_id BIGINT;
    v_available INTEGER;
    v_old_version BIGINT;
BEGIN
    IF p_quantity IS NULL OR p_quantity <= 0 THEN
        RAISE EXCEPTION
            'Reservation quantity must be positive';
    END IF;

    -- SELECT FOR UPDATE obtains an exclusive row-level lock.
    -- The lock remains until the surrounding transaction ends.
    SELECT
        inventory_id,
        available_quantity,
        version_number
    INTO
        v_inventory_id,
        v_available,
        v_old_version
    FROM inventory
    WHERE product_code = p_product_code
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN FALSE;
    END IF;

    IF v_available < p_quantity THEN
        RETURN FALSE;
    END IF;

    UPDATE inventory
    SET available_quantity = available_quantity - p_quantity,
        version_number = version_number + 1
    WHERE inventory_id = v_inventory_id;

    INSERT INTO concurrency_events (
        transaction_reference,
        event_type,
        event_details
    )
    VALUES (
        gen_random_uuid(),
        'LOCKED_RESERVATION',
        jsonb_build_object(
            'inventory_id', v_inventory_id,
            'quantity', p_quantity,
            'old_version', v_old_version
        )
    );

    RETURN TRUE;
END;
$$;


-- ------------------------------------------------------------
-- 8. OPTIMISTIC CONCURRENCY FUNCTION
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION reserve_inventory_optimistic(
    p_inventory_id BIGINT,
    p_expected_version BIGINT,
    p_quantity INTEGER
)
RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
DECLARE
    v_updated INTEGER;
BEGIN
    IF p_quantity IS NULL OR p_quantity <= 0 THEN
        RAISE EXCEPTION
            'Reservation quantity must be positive';
    END IF;

    IF p_expected_version IS NULL OR p_expected_version <= 0 THEN
        RAISE EXCEPTION
            'Expected version must be positive';
    END IF;

    -- Compare-and-swap style update.
    --
    -- The expected version prevents a stale client from
    -- silently overwriting a concurrent modification.
    --
    -- PostgreSQL still obtains the required internal row lock
    -- when executing the UPDATE.
    UPDATE inventory
    SET available_quantity = available_quantity - p_quantity,
        version_number = version_number + 1
    WHERE inventory_id = p_inventory_id
      AND version_number = p_expected_version
      AND available_quantity >= p_quantity;

    GET DIAGNOSTICS v_updated = ROW_COUNT;

    IF v_updated = 0 THEN
        INSERT INTO concurrency_events (
            transaction_reference,
            event_type,
            event_details
        )
        VALUES (
            gen_random_uuid(),
            'OPTIMISTIC_CONFLICT',
            jsonb_build_object(
                'inventory_id', p_inventory_id,
                'expected_version', p_expected_version,
                'quantity', p_quantity
            )
        );

        RETURN FALSE;
    END IF;

    RETURN TRUE;
END;
$$;


-- ------------------------------------------------------------
-- 9. MULTI-ROW LOCKING WITH DETERMINISTIC LOCK ORDER
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION transfer_inventory_locked(
    p_source_id BIGINT,
    p_destination_id BIGINT,
    p_quantity INTEGER
)
RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
DECLARE
    v_source_quantity INTEGER;
    v_destination_quantity INTEGER;
    v_first_id BIGINT;
    v_second_id BIGINT;
BEGIN
    IF p_quantity IS NULL OR p_quantity <= 0 THEN
        RAISE EXCEPTION
            'Transfer quantity must be positive';
    END IF;

    IF p_source_id = p_destination_id THEN
        RAISE EXCEPTION
            'Source and destination must differ';
    END IF;

    v_first_id := LEAST(p_source_id, p_destination_id);
    v_second_id := GREATEST(p_source_id, p_destination_id);

    -- Lock records in the same order across transactions.
    -- This reduces deadlock risk for opposing transfers.
    PERFORM inventory_id
    FROM inventory
    WHERE inventory_id IN (v_first_id, v_second_id)
    ORDER BY inventory_id
    FOR UPDATE;

    IF (
        SELECT COUNT(*)
        FROM inventory
        WHERE inventory_id IN (p_source_id, p_destination_id)
    ) <> 2 THEN
        RETURN FALSE;
    END IF;

    SELECT available_quantity
    INTO v_source_quantity
    FROM inventory
    WHERE inventory_id = p_source_id;

    SELECT available_quantity
    INTO v_destination_quantity
    FROM inventory
    WHERE inventory_id = p_destination_id;

    IF v_source_quantity < p_quantity THEN
        RETURN FALSE;
    END IF;

    UPDATE inventory
    SET available_quantity = available_quantity - p_quantity,
        version_number = version_number + 1
    WHERE inventory_id = p_source_id;

    UPDATE inventory
    SET available_quantity = available_quantity + p_quantity,
        version_number = version_number + 1
    WHERE inventory_id = p_destination_id;

    RETURN TRUE;
END;
$$;


