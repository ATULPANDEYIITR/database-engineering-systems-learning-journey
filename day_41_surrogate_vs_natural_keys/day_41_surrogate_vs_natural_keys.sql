-- A reporting query resolves the stable foreign key to mutable business data.
SELECT
    c.customer_id,
    c.legal_name,
    c.country_code,
    c.tax_identifier,
    o.order_id,
    o.source_system,
    o.source_order_id,
    o.amount_minor_units
FROM customers AS c
JOIN orders AS o
    ON o.customer_id = c.customer_id
ORDER BY c.customer_id, o.source_order_id;

-- Compare the number of internal customers with the number of external
-- identities. One customer may legitimately have identities in many systems.
SELECT
    c.customer_id,
    c.legal_name,
    COUNT(e.external_id) AS external_identity_count
FROM customers AS c
LEFT JOIN customer_external_ids AS e
    ON e.customer_id = c.customer_id
GROUP BY c.customer_id, c.legal_name
ORDER BY c.customer_id;

-- Detect duplicate natural identifiers in an imported staging dataset
-- before attempting insertion into the constrained master table.
WITH incoming_tax_records(country_code, tax_identifier, legal_name) AS (
    VALUES
        ('IN', 'GST-29-ACME-001', 'Duplicate Imported Record'),
        ('IN', 'GST-29-ACME-777', 'New Imported Entity'),
        ('US', 'EIN-12-3456789', 'Existing US Entity')
)
SELECT
    country_code,
    tax_identifier,
    COUNT(*) AS source_row_count,
    ARRAY_AGG(legal_name ORDER BY legal_name) AS names
FROM incoming_tax_records
GROUP BY country_code, tax_identifier
HAVING COUNT(*) > 1;

-- Find natural-key collisions between incoming records and the master table.
WITH incoming_tax_records(country_code, tax_identifier, legal_name) AS (
    VALUES
        ('IN', 'GST-29-ACME-001', 'Duplicate Imported Record'),
        ('IN', 'GST-29-ACME-777', 'New Imported Entity'),
        ('US', 'EIN-12-3456789', 'Existing US Entity')
)
SELECT
    i.country_code,
    i.tax_identifier,
    i.legal_name AS incoming_name,
    c.customer_id,
    c.legal_name AS existing_name
FROM incoming_tax_records AS i
JOIN customers AS c
    ON c.country_code = i.country_code
   AND c.tax_identifier = i.tax_identifier
ORDER BY i.country_code, i.tax_identifier;

-- Demonstrate a natural-key correction without changing customer_id.
-- The trigger records the old and new business identity in the audit table.
UPDATE customers
SET tax_identifier = 'GST-29-ACME-009'
WHERE country_code = 'IN'
  AND tax_identifier = 'GST-29-ACME-001';

SELECT
    customer_id,
    legal_name,
    country_code,
    tax_identifier
FROM customers
WHERE country_code = 'IN';

SELECT *
FROM customer_key_audit
ORDER BY audit_id;

-- Merge eligibility is not a database-key concern, but the same principle
-- applies: keep independently meaningful identities in separate columns.
-- The query below verifies source-key uniqueness and referential integrity.
SELECT
    o.source_system,
    o.source_order_id,
    COUNT(*) AS order_count,
    COUNT(DISTINCT o.customer_id) AS distinct_customers
FROM orders AS o
GROUP BY o.source_system, o.source_order_id
HAVING COUNT(*) > 1
    OR COUNT(DISTINCT o.customer_id) > 1;

COMMIT;

