-- PostgreSQL 15+.
-- Surrogate and natural keys in a customer, order, and source-reconciliation
-- system. The surrogate customer ID is the stable relational identity.
-- Natural identifiers and external source identifiers have independent
-- uniqueness rules because they represent different business contracts.

BEGIN;

CREATE SCHEMA IF NOT EXISTS key_design_lab;
SET LOCAL search_path TO key_design_lab, public;

CREATE TABLE IF NOT EXISTS customers (
    customer_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    legal_name TEXT NOT NULL CHECK (length(btrim(legal_name)) > 0),
    country_code CHAR(2) NOT NULL
        CHECK (country_code ~ '^[A-Z]{2}$'),
    tax_identifier TEXT NOT NULL
        CHECK (length(btrim(tax_identifier)) > 0),
    email TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- The pair is a natural key only if the applicable jurisdiction
    -- guarantees uniqueness. It remains a candidate key even though the
    -- surrogate primary key is used by dependent tables.
    CONSTRAINT uq_customer_tax_identity
        UNIQUE (country_code, tax_identifier),

    CONSTRAINT uq_customer_email
        UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS customer_external_ids (
    external_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL
        REFERENCES customers(customer_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,
    source_system TEXT NOT NULL
        CHECK (length(btrim(source_system)) > 0),
    source_record_id TEXT NOT NULL
        CHECK (length(btrim(source_record_id)) > 0),
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- The source-system/record pair identifies a record in its own system.
    -- It is not the same as the internal customer identity.
    CONSTRAINT uq_external_customer_source
        UNIQUE (source_system, source_record_id)
);

CREATE TABLE IF NOT EXISTS orders (
    order_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id BIGINT NOT NULL
        REFERENCES customers(customer_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,
    source_system TEXT NOT NULL,
    source_order_id TEXT NOT NULL,
    amount_minor_units BIGINT NOT NULL
        CHECK (amount_minor_units >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_order_source
        UNIQUE (source_system, source_order_id),

    CONSTRAINT ck_order_source_nonempty
        CHECK (
            length(btrim(source_system)) > 0
            AND length(btrim(source_order_id)) > 0
        )
);

CREATE INDEX IF NOT EXISTS idx_orders_customer_created
    ON orders (customer_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_external_ids_customer
    ON customer_external_ids (customer_id);

CREATE TABLE IF NOT EXISTS customer_key_audit (
    audit_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    old_country_code CHAR(2) NOT NULL,
    old_tax_identifier TEXT NOT NULL,
    new_country_code CHAR(2) NOT NULL,
    new_tax_identifier TEXT NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    change_reason TEXT NOT NULL
        CHECK (length(btrim(change_reason)) > 0)
);

CREATE OR REPLACE FUNCTION audit_customer_natural_key_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.country_code IS DISTINCT FROM NEW.country_code
       OR OLD.tax_identifier IS DISTINCT FROM NEW.tax_identifier THEN

        INSERT INTO customer_key_audit (
            customer_id,
            old_country_code,
            old_tax_identifier,
            new_country_code,
            new_tax_identifier,
            change_reason
        )
        VALUES (
            OLD.customer_id,
            OLD.country_code,
            OLD.tax_identifier,
            NEW.country_code,
            NEW.tax_identifier,
            'Natural-key correction recorded by database trigger'
        );
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_audit_customer_natural_key
    ON customers;

CREATE TRIGGER trg_audit_customer_natural_key
AFTER UPDATE OF country_code, tax_identifier ON customers
FOR EACH ROW
EXECUTE FUNCTION audit_customer_natural_key_change();

