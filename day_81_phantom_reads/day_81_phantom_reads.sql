-- ================================================================
-- 11. CTE-BASED RANGE ANALYSIS
-- ================================================================

WITH eligible_products AS (
    SELECT
        product_id,
        product_name,
        category,
        price
    FROM products
    WHERE active = TRUE
      AND price >= 500
      AND price < 5000
),
category_statistics AS (
    SELECT
        category,
        COUNT(*) AS matching_products,
        AVG(price) AS average_price
    FROM eligible_products
    GROUP BY category
)
SELECT
    category,
    matching_products,
    ROUND(average_price, 2) AS average_price
FROM category_statistics
ORDER BY category;

