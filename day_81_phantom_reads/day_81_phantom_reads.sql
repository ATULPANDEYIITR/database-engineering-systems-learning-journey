-- ================================================================
-- 3. AUDIT TRIGGER
-- ================================================================

CREATE OR REPLACE FUNCTION audit_product_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO transaction_audit (
            product_id,
            operation,
            old_price,
            new_price
        )
        VALUES (
            NEW.product_id,
            'INSERT',
            NULL,
            NEW.price
        );

        RETURN NEW;

    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO transaction_audit (
            product_id,
            operation,
            old_price,
            new_price
        )
        VALUES (
            NEW.product_id,
            'UPDATE',
            OLD.price,
            NEW.price
        );

        NEW.updated_at := CURRENT_TIMESTAMP;

        RETURN NEW;

    ELSIF TG_OP = 'DELETE' THEN
        INSERT INTO transaction_audit (
            product_id,
            operation,
            old_price,
            new_price
        )
        VALUES (
            OLD.product_id,
            'DELETE',
            OLD.price,
            NULL
        );

        RETURN OLD;
    END IF;

    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_product_audit ON products;

CREATE TRIGGER trg_product_audit
AFTER INSERT OR UPDATE OR DELETE
ON products
FOR EACH ROW
EXECUTE FUNCTION audit_product_change();

-- ================================================================
-- 4. RANGE QUERY FUNCTION
-- ================================================================

CREATE OR REPLACE FUNCTION get_products_in_range(
    p_minimum NUMERIC,
    p_maximum NUMERIC
)
RETURNS TABLE (
    product_id BIGINT,
    product_name VARCHAR(150),
    category VARCHAR(80),
    price NUMERIC(12, 2)
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    IF p_minimum IS NULL OR p_maximum IS NULL THEN
        RAISE EXCEPTION 'Range boundaries cannot be NULL';
    END IF;

    IF p_minimum > p_maximum THEN
        RAISE EXCEPTION 'Minimum price exceeds maximum price';
    END IF;

    RETURN QUERY
    SELECT
        p.product_id,
        p.product_name,
        p.category,
        p.price
    FROM products p
    WHERE p.active = TRUE
      AND p.price >= p_minimum
      AND p.price < p_maximum
    ORDER BY p.price, p.product_id;
END;
$$;

-- ================================================================
-- 5. ELIGIBILITY EVALUATION
-- ================================================================

CREATE OR REPLACE FUNCTION is_price_range_eligible(
    p_product_id BIGINT,
    p_minimum NUMERIC,
    p_maximum NUMERIC
)
RETURNS BOOLEAN
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    eligible BOOLEAN;
BEGIN
    IF p_minimum > p_maximum THEN
        RAISE EXCEPTION 'Invalid price range';
    END IF;

    SELECT EXISTS (
        SELECT 1
        FROM products
        WHERE product_id = p_product_id
          AND active = TRUE
          AND price >= p_minimum
          AND price < p_maximum
    )
    INTO eligible;

    RETURN eligible;
END;
$$;

-- ================================================================
-- 6. TRANSACTIONAL PRICE UPDATE PROCEDURE
-- ================================================================

CREATE OR REPLACE PROCEDURE update_product_price(
    p_product_id BIGINT,
    p_new_price NUMERIC
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_new_price IS NULL OR p_new_price < 0 THEN
        RAISE EXCEPTION 'Invalid product price';
    END IF;

    UPDATE products
    SET price = p_new_price
    WHERE product_id = p_product_id
      AND active = TRUE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Active product % does not exist',
            p_product_id;
    END IF;
END;
$$;

-- ================================================================
-- 7. REPORTING VIEW
-- ================================================================

CREATE OR REPLACE VIEW price_range_report AS
SELECT
    category,
    COUNT(*) AS product_count,
    MIN(price) AS minimum_price,
    MAX(price) AS maximum_price,
    AVG(price)::NUMERIC(12, 2) AS average_price,
    SUM(price)::NUMERIC(14, 2) AS total_inventory_value
FROM products
WHERE active = TRUE
GROUP BY category;

