-- ================================================================
-- 16. PHANTOM READ EXPERIMENT
--
-- IMPORTANT:
-- Open TWO independent PostgreSQL sessions.
--
-- The following sequences must be interleaved manually.
-- They are not a single-session experiment.
-- ================================================================

-- SESSION A:
--
-- BEGIN ISOLATION LEVEL READ COMMITTED;
--
-- SELECT COUNT(*)
-- FROM phantom_lab.products
-- WHERE active = TRUE
--   AND price >= 500
--   AND price < 5000;
--
-- SESSION B:
--
-- BEGIN;
--
-- INSERT INTO phantom_lab.products (
--     product_id,
--     product_name,
--     category,
--     price
-- )
-- VALUES (
--     200,
--     'Phantom Product',
--     'Electronics',
--     2500
-- );
--
-- COMMIT;
--
-- SESSION A:
--
-- SELECT COUNT(*)
-- FROM phantom_lab.products
-- WHERE active = TRUE
--   AND price >= 500
--   AND price < 5000;
--
-- The second SELECT can return a larger count.
-- This is a phantom read under READ COMMITTED.

-- ================================================================
-- 17. REPEATABLE READ EXPERIMENT
-- ================================================================

-- SESSION A:
--
-- BEGIN ISOLATION LEVEL REPEATABLE READ;
--
-- SELECT product_id, product_name, price
-- FROM phantom_lab.products
-- WHERE active = TRUE
--   AND price >= 500
--   AND price < 5000;
--
-- SESSION B:
--
-- BEGIN;
--
-- INSERT INTO phantom_lab.products (
--     product_id,
--     product_name,
--     category,
--     price
-- )
-- VALUES (
--     201,
--     'Snapshot Test Product',
--     'Electronics',
--     2600
-- );
--
-- COMMIT;
--
-- SESSION A:
--
-- SELECT product_id, product_name, price
-- FROM phantom_lab.products
-- WHERE active = TRUE
--   AND price >= 500
--   AND price < 5000;
--
-- SESSION A continues to use its original transaction snapshot.
-- The second query does not see the newly committed row.
--
-- COMMIT;

-- ================================================================
-- 18. SERIALIZABLE EXPERIMENT
-- ================================================================

-- SESSION A:
--
-- BEGIN ISOLATION LEVEL SERIALIZABLE;
--
-- SELECT COUNT(*)
-- FROM phantom_lab.products
-- WHERE active = TRUE
--   AND price >= 500
--   AND price < 5000;
--
-- SESSION B:
--
-- BEGIN ISOLATION LEVEL SERIALIZABLE;
--
-- INSERT INTO phantom_lab.products (
--     product_id,
--     product_name,
--     category,
--     price
-- )
-- VALUES (
--     202,
--     'Serializable Test Product',
--     'Electronics',
--     2700
-- );
--
-- COMMIT;
--
-- SESSION A:
--
-- UPDATE phantom_lab.products
-- SET price = price + 1
-- WHERE product_id = 1;
--
-- COMMIT;
--
-- Depending on the concurrent execution schedule, PostgreSQL may
-- abort one transaction with SQLSTATE 40001
-- (serialization_failure).
--
-- SERIALIZABLE uses Serializable Snapshot Isolation (SSI).
-- PostgreSQL tracks predicate conflicts and dangerous dependency
-- structures. It does not simply acquire a conventional table-wide
-- lock for every range query.

-- ================================================================
-- 19. SERIALIZABLE RETRY PATTERN
-- ================================================================

-- Execute this transaction in an application with retry handling.
--
-- BEGIN ISOLATION LEVEL SERIALIZABLE;
--
-- SELECT COUNT(*)
-- FROM phantom_lab.products
-- WHERE active = TRUE
--   AND price >= 500
--   AND price < 5000;
--
-- UPDATE phantom_lab.products
-- SET updated_at = CURRENT_TIMESTAMP
-- WHERE product_id = 1;
--
-- COMMIT;
--
-- If SQLSTATE 40001 occurs:
--   1. Roll back the complete transaction.
--   2. Start a new transaction.
--   3. Repeat every read and write.
--   4. Apply bounded retries with backoff.
--
-- Do not retry only the failed statement.

-- ================================================================
-- 20. QUERY PERFORMANCE INSPECTION
-- ================================================================

EXPLAIN (COSTS, VERBOSE)
SELECT
    product_id,
    product_name,
    price
FROM products
WHERE active = TRUE
  AND price >= 500
  AND price < 5000
ORDER BY price, product_id;

