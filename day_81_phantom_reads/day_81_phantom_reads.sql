-- ================================================================
-- PHANTOM READS
-- Range Queries and Transaction Isolation
-- PostgreSQL 15+
--
-- Demonstrates:
--   1. Relational modeling of inventory records.
--   2. Range-query execution.
--   3. Read Committed statement snapshots.
--   4. Repeatable Read transaction snapshots.
--   5. Serializable isolation and serialization failures.
--   6. Transaction retries.
--   7. Audit logging.
--   8. Predicate-based reporting.
--
-- Execute this setup script using psql.
-- Concurrent isolation demonstrations require two sessions.
-- ================================================================

CREATE SCHEMA IF NOT EXISTS phantom_lab;

SET search_path TO phantom_lab, public;

-- ================================================================
-- 1. DOMAIN TABLES
-- ================================================================

CREATE TABLE IF NOT EXISTS products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_name VARCHAR(150) NOT NULL,

    category VARCHAR(80) NOT NULL,

    price NUMERIC(12, 2) NOT NULL,

    active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT products_name_not_empty
        CHECK (length(trim(product_name)) > 0),

    CONSTRAINT products_category_not_empty
        CHECK (length(trim(category)) > 0),

    CONSTRAINT products_price_nonnegative
        CHECK (price >= 0)
);

CREATE TABLE IF NOT EXISTS transaction_audit (
    audit_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    transaction_id BIGINT NOT NULL DEFAULT txid_current(),

    product_id BIGINT,

    operation VARCHAR(10) NOT NULL,

    old_price NUMERIC(12, 2),

    new_price NUMERIC(12, 2),

    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT audit_operation_valid
        CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE'))
);

-- Price-range queries use this index.
CREATE INDEX IF NOT EXISTS idx_products_active_price
    ON products(price, product_id)
    WHERE active = TRUE;

CREATE INDEX IF NOT EXISTS idx_products_category_price
    ON products(category, price)
    WHERE active = TRUE;

CREATE INDEX IF NOT EXISTS idx_audit_product_time
    ON transaction_audit(product_id, changed_at DESC);

