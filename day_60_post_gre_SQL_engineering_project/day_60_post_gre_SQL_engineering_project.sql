-- PostgreSQL production-style order management and operations database.
--
-- Baseline: PostgreSQL 14 or later.
-- Execute as the schema owner or a database administrator:
--   psql -X -v ON_ERROR_STOP=1 -f postgresql.sql
--
-- The script is transactional and safe to rerun for its sample data.
-- It does not create login roles or change server-wide configuration.
--
-- IMPORTANT SECURITY BOUNDARY:
-- app.current_tenant_id() reads the app.tenant_id session setting.
-- The application must set this value from an authenticated tenant context.
-- Do not expose unrestricted SQL access to users who can choose this setting.
-- For untrusted direct database clients, use database-role-based tenant
-- identity or another independently authenticated tenant mapping.

BEGIN;

DO $$
BEGIN
    IF current_setting('server_version_num')::integer < 140000 THEN
        RAISE EXCEPTION
            'PostgreSQL 14 or later is required. Found server_version_num=%',
            current_setting('server_version_num');
    END IF;
END;
$$;

CREATE SCHEMA IF NOT EXISTS app;
CREATE SCHEMA IF NOT EXISTS ops;

REVOKE ALL ON SCHEMA app FROM PUBLIC;
REVOKE ALL ON SCHEMA ops FROM PUBLIC;

DO $$
BEGIN
    CREATE TYPE app.order_status AS ENUM (
        'draft',
        'reserved',
        'fulfilled',
        'cancelled'
    );
EXCEPTION
    WHEN duplicate_object THEN NULL;
END;
$$;

CREATE TABLE IF NOT EXISTS app.tenant (
    tenant_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_name text NOT NULL UNIQUE,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT tenant_name_not_blank
        CHECK (btrim(tenant_name) <> '')
);

CREATE TABLE IF NOT EXISTS app.customer (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL REFERENCES app.tenant(tenant_id),
    email text NOT NULL,
    display_name text NOT NULL,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT customer_email_normalized
        CHECK (
            email = lower(email)
            AND position('@' IN email) > 1
            AND position(' ' IN email) = 0
        ),
    CONSTRAINT customer_display_name_not_blank
        CHECK (btrim(display_name) <> ''),
    CONSTRAINT customer_tenant_email_unique
        UNIQUE (tenant_id, email),
    CONSTRAINT customer_tenant_customer_unique
        UNIQUE (tenant_id, customer_id)
);

CREATE TABLE IF NOT EXISTS app.product (
    product_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku text NOT NULL UNIQUE,
    product_name text NOT NULL,
    unit_price numeric(12, 2) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT product_sku_format
        CHECK (sku ~ '^[A-Z0-9-]{3,32}$'),
    CONSTRAINT product_name_not_blank
        CHECK (btrim(product_name) <> ''),
    CONSTRAINT product_price_nonnegative
        CHECK (unit_price >= 0)
);

CREATE TABLE IF NOT EXISTS app.warehouse (
    warehouse_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_code text NOT NULL UNIQUE,
    warehouse_name text NOT NULL,
    active boolean NOT NULL DEFAULT true,
    CONSTRAINT warehouse_code_not_blank
        CHECK (btrim(warehouse_code) <> ''),
    CONSTRAINT warehouse_name_not_blank
        CHECK (btrim(warehouse_name) <> '')
);

CREATE TABLE IF NOT EXISTS app.inventory (
    warehouse_id bigint NOT NULL
        REFERENCES app.warehouse(warehouse_id),
    product_id bigint NOT NULL
        REFERENCES app.product(product_id),
    on_hand integer NOT NULL DEFAULT 0,
    reserved integer NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (warehouse_id, product_id),
    CONSTRAINT inventory_on_hand_nonnegative
        CHECK (on_hand >= 0),
    CONSTRAINT inventory_reserved_nonnegative
        CHECK (reserved >= 0),
    CONSTRAINT inventory_reserved_not_above_stock
        CHECK (reserved <= on_hand)
);

CREATE TABLE IF NOT EXISTS app.sales_order (
    order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    customer_id bigint NOT NULL,
    order_status app.order_status NOT NULL DEFAULT 'draft',
    currency text NOT NULL DEFAULT 'INR',
    total numeric(14, 2) NOT NULL DEFAULT 0,
    idempotency_key varchar(128) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT sales_order_customer_fk
        FOREIGN KEY (tenant_id, customer_id)
        REFERENCES app.customer(tenant_id, customer_id),
    CONSTRAINT sales_order_total_nonnegative
        CHECK (total >= 0),
    CONSTRAINT sales_order_currency_format
        CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT sales_order_idempotency_not_blank
        CHECK (btrim(idempotency_key) <> ''),
    CONSTRAINT sales_order_tenant_key_unique
        UNIQUE (tenant_id, idempotency_key)
);

CREATE TABLE IF NOT EXISTS app.order_item (
    order_id bigint NOT NULL
        REFERENCES app.sales_order(order_id),
    line_no integer NOT NULL,
    product_id bigint NOT NULL
        REFERENCES app.product(product_id),
    quantity integer NOT NULL,
    unit_price numeric(12, 2) NOT NULL,
    line_total numeric(14, 2)
        GENERATED ALWAYS AS (quantity * unit_price) STORED,
    PRIMARY KEY (order_id, line_no),
    CONSTRAINT order_item_line_number_positive
        CHECK (line_no > 0),
    CONSTRAINT order_item_quantity_positive
        CHECK (quantity > 0 AND quantity <= 100000),
    CONSTRAINT order_item_unit_price_nonnegative
        CHECK (unit_price >= 0),
    CONSTRAINT order_item_product_once_per_order
        UNIQUE (order_id, product_id)
);

CREATE TABLE IF NOT EXISTS app.order_reservation (
    order_id bigint NOT NULL,
    line_no integer NOT NULL,
    warehouse_id bigint NOT NULL,
    product_id bigint NOT NULL,
    quantity integer NOT NULL,
    reservation_state text NOT NULL DEFAULT 'reserved',
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (order_id, line_no),
    CONSTRAINT reservation_item_fk
        FOREIGN KEY (order_id, line_no)
        REFERENCES app.order_item(order_id, line_no),
    CONSTRAINT reservation_inventory_fk
        FOREIGN KEY (warehouse_id, product_id)
        REFERENCES app.inventory(warehouse_id, product_id),
    CONSTRAINT reservation_quantity_positive
        CHECK (quantity > 0),
    CONSTRAINT reservation_state_valid
        CHECK (
            reservation_state IN ('reserved', 'consumed', 'released')
        )
);

