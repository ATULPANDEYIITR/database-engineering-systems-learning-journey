-- This function centralizes the session tenant lookup used by RLS policies.
CREATE OR REPLACE FUNCTION app.current_tenant_id()
RETURNS bigint
LANGUAGE sql
STABLE
AS $$
    SELECT NULLIF(
        current_setting('app.tenant_id', true),
        ''
    )::bigint;
$$;

CREATE OR REPLACE FUNCTION app.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION app.enforce_order_status_transition()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.order_status = OLD.order_status THEN
        RETURN NEW;
    END IF;

    IF NOT (
        (OLD.order_status = 'draft'
            AND NEW.order_status IN ('reserved', 'cancelled'))
        OR
        (OLD.order_status = 'reserved'
            AND NEW.order_status IN ('fulfilled', 'cancelled'))
    ) THEN
        RAISE EXCEPTION
            'Invalid order transition: % -> %',
            OLD.order_status,
            NEW.order_status
            USING ERRCODE = 'P0001';
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION app.guard_order_item_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_order_id bigint;
    v_status app.order_status;
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_order_id := OLD.order_id;
    ELSE
        v_order_id := NEW.order_id;
    END IF;

    IF TG_OP = 'UPDATE' AND NEW.order_id <> OLD.order_id THEN
        RAISE EXCEPTION
            'An order item cannot be moved to another order'
            USING ERRCODE = 'P0001';
    END IF;

    SELECT order_status
      INTO v_status
      FROM app.sales_order
     WHERE order_id = v_order_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Order % was not found or is not visible',
            v_order_id
            USING ERRCODE = 'P0002';
    END IF;

    IF v_status <> 'draft' THEN
        RAISE EXCEPTION
            'Order items can only be changed while an order is draft'
            USING ERRCODE = 'P0001';
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

-- A row-level trigger keeps the stored order total synchronized.
-- A separate statement-level batch calculation could be used for high-volume
-- imports to avoid recalculating once for every inserted line.
CREATE OR REPLACE FUNCTION app.recalculate_order_total()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, app
AS $$
DECLARE
    v_order_id bigint;
    v_total numeric(14, 2);
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_order_id := OLD.order_id;
    ELSE
        v_order_id := NEW.order_id;
    END IF;

    SELECT COALESCE(sum(line_total), 0)::numeric(14, 2)
      INTO v_total
      FROM app.order_item
     WHERE order_id = v_order_id;

    UPDATE app.sales_order
       SET total = v_total
     WHERE order_id = v_order_id;

    RETURN NULL;
END;
$$;

-- Keep audit data small and avoid copying customer details or credentials.
CREATE OR REPLACE FUNCTION app.audit_order_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, app
AS $$
DECLARE
    v_details jsonb;
BEGIN
    IF TG_OP = 'INSERT' THEN
        v_details := jsonb_build_object(
            'tenant_id', NEW.tenant_id,
            'status', NEW.order_status,
            'total', NEW.total,
            'currency', NEW.currency
        );

        INSERT INTO app.audit_log (
            entity_type,
            entity_id,
            operation,
            details
        )
        VALUES (
            'sales_order',
            NEW.order_id,
            'INSERT',
            v_details
        );

        RETURN NEW;
    END IF;

    v_details := jsonb_build_object(
        'tenant_id', NEW.tenant_id,
        'old_status', OLD.order_status,
        'new_status', NEW.order_status,
        'old_total', OLD.total,
        'new_total', NEW.total
    );

    INSERT INTO app.audit_log (
        entity_type,
        entity_id,
        operation,
        details
    )
    VALUES (
        'sales_order',
        NEW.order_id,
        'UPDATE',
        v_details
    );

    RETURN NEW;
END;
$$;

