-- Operational views are placed in a restricted schema. The inventory view
-- exposes aggregate stock quantities, not tenant-owned customer information.
CREATE OR REPLACE VIEW ops.v_inventory_availability AS
SELECT
    warehouse.warehouse_code,
    product.sku,
    product.product_name,
    inventory.on_hand,
    inventory.reserved,
    inventory.on_hand - inventory.reserved AS available
FROM app.inventory AS inventory
JOIN app.warehouse AS warehouse
  ON warehouse.warehouse_id = inventory.warehouse_id
JOIN app.product AS product
  ON product.product_id = inventory.product_id;

CREATE OR REPLACE VIEW ops.v_order_status_counts AS
SELECT
    tenant_id,
    order_status,
    count(*) AS order_count,
    sum(total) AS order_value
FROM app.sales_order
GROUP BY tenant_id, order_status;

