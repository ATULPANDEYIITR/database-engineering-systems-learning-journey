-- Create representative reserved, fulfilled and cancelled states.
-- Existing completed states are not processed a second time on reruns.
DO $$
DECLARE
    v_order_id bigint;
    v_status app.order_status;
BEGIN
    SELECT order_id, order_status
      INTO v_order_id, v_status
      FROM app.sales_order
     WHERE tenant_id = 1
       AND idempotency_key = 'seed-reserved';

    IF v_status = 'draft' THEN
        PERFORM app.reserve_order(v_order_id, 1);
    END IF;

    SELECT order_id, order_status
      INTO v_order_id, v_status
      FROM app.sales_order
     WHERE tenant_id = 1
       AND idempotency_key = 'seed-fulfilled';

    IF v_status = 'draft' THEN
        PERFORM app.reserve_order(v_order_id, 1);
        v_status := 'reserved';
    END IF;

    IF v_status = 'reserved' THEN
        PERFORM app.fulfill_order(v_order_id);
    END IF;

    SELECT order_id, order_status
      INTO v_order_id, v_status
      FROM app.sales_order
     WHERE tenant_id = 1
       AND idempotency_key = 'seed-cancelled';

    IF v_status IN ('draft', 'reserved') THEN
        PERFORM app.cancel_order(v_order_id);
    END IF;
END;
$$;

