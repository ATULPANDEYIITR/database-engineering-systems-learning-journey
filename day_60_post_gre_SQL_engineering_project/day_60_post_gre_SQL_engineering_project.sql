-- Reserve stock in deterministic product order to reduce deadlock risk.
-- The entire operation belongs to the caller's transaction. A failed item
-- reservation raises an exception and leaves no partial reservation after
-- the transaction is rolled back.
CREATE OR REPLACE FUNCTION app.reserve_order(
    p_order_id bigint,
    p_warehouse_id bigint
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, app
AS $$
DECLARE
    v_order app.sales_order%ROWTYPE;
    v_item record;
    v_processed integer := 0;
BEGIN
    IF p_order_id <= 0 OR p_warehouse_id <= 0 THEN
        RAISE EXCEPTION 'Order and warehouse IDs must be positive'
            USING ERRCODE = '22023';
    END IF;

    SELECT *
      INTO v_order
      FROM app.sales_order
     WHERE order_id = p_order_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Order not found or not visible'
            USING ERRCODE = 'P0002';
    END IF;

    IF v_order.tenant_id <> app.current_tenant_id() THEN
        RAISE EXCEPTION 'Tenant context does not match the order'
            USING ERRCODE = '42501';
    END IF;

    IF v_order.order_status <> 'draft' THEN
        RAISE EXCEPTION 'Only draft orders can reserve stock'
            USING ERRCODE = 'P0001';
    END IF;

    FOR v_item IN
        SELECT
            line_no,
            product_id,
            quantity
        FROM app.order_item
        WHERE order_id = p_order_id
        ORDER BY product_id, line_no
        FOR UPDATE
    LOOP
        UPDATE app.inventory
           SET reserved = reserved + v_item.quantity,
               updated_at = clock_timestamp()
         WHERE warehouse_id = p_warehouse_id
           AND product_id = v_item.product_id
           AND on_hand - reserved >= v_item.quantity;

        IF NOT FOUND THEN
            RAISE EXCEPTION
                'Insufficient stock for product % in warehouse %',
                v_item.product_id,
                p_warehouse_id
                USING ERRCODE = 'P0001';
        END IF;

        INSERT INTO app.order_reservation (
            order_id,
            line_no,
            warehouse_id,
            product_id,
            quantity,
            reservation_state
        )
        VALUES (
            p_order_id,
            v_item.line_no,
            p_warehouse_id,
            v_item.product_id,
            v_item.quantity,
            'reserved'
        );

        v_processed := v_processed + 1;
    END LOOP;

    IF v_processed = 0 THEN
        RAISE EXCEPTION 'An order without items cannot be reserved'
            USING ERRCODE = 'P0001';
    END IF;

    UPDATE app.sales_order
       SET order_status = 'reserved'
     WHERE order_id = p_order_id;
END;
$$;

-- Fulfillment reduces on-hand stock and reserved stock together.
CREATE OR REPLACE FUNCTION app.fulfill_order(
    p_order_id bigint
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, app
AS $$
DECLARE
    v_order app.sales_order%ROWTYPE;
    v_reservation record;
    v_processed integer := 0;
BEGIN
    IF p_order_id <= 0 THEN
        RAISE EXCEPTION 'Order ID must be positive'
            USING ERRCODE = '22023';
    END IF;

    SELECT *
      INTO v_order
      FROM app.sales_order
     WHERE order_id = p_order_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Order not found or not visible'
            USING ERRCODE = 'P0002';
    END IF;

    IF v_order.tenant_id <> app.current_tenant_id() THEN
        RAISE EXCEPTION 'Tenant context does not match the order'
            USING ERRCODE = '42501';
    END IF;

    IF v_order.order_status <> 'reserved' THEN
        RAISE EXCEPTION 'Only reserved orders can be fulfilled'
            USING ERRCODE = 'P0001';
    END IF;

    FOR v_reservation IN
        SELECT
            order_id,
            line_no,
            warehouse_id,
            product_id,
            quantity
        FROM app.order_reservation
        WHERE order_id = p_order_id
          AND reservation_state = 'reserved'
        ORDER BY product_id, warehouse_id, line_no
        FOR UPDATE
    LOOP
        UPDATE app.inventory
           SET on_hand = on_hand - v_reservation.quantity,
               reserved = reserved - v_reservation.quantity,
               updated_at = clock_timestamp()
         WHERE warehouse_id = v_reservation.warehouse_id
           AND product_id = v_reservation.product_id
           AND on_hand >= v_reservation.quantity
           AND reserved >= v_reservation.quantity;

        IF NOT FOUND THEN
            RAISE EXCEPTION
                'Inventory invariant failed for product %',
                v_reservation.product_id
                USING ERRCODE = 'P0001';
        END IF;

        UPDATE app.order_reservation
           SET reservation_state = 'consumed'
         WHERE order_id = v_reservation.order_id
           AND line_no = v_reservation.line_no;

        v_processed := v_processed + 1;
    END LOOP;

    IF v_processed = 0 THEN
        RAISE EXCEPTION 'No active reservations exist for this order'
            USING ERRCODE = 'P0001';
    END IF;

    UPDATE app.sales_order
       SET order_status = 'fulfilled'
     WHERE order_id = p_order_id;
END;
$$;

-- Cancellation releases active reservations. A fulfilled order cannot be
-- cancelled through this workflow because stock has already been consumed.
CREATE OR REPLACE FUNCTION app.cancel_order(
    p_order_id bigint
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, app
AS $$
DECLARE
    v_order app.sales_order%ROWTYPE;
    v_reservation record;
BEGIN
    IF p_order_id <= 0 THEN
        RAISE EXCEPTION 'Order ID must be positive'
            USING ERRCODE = '22023';
    END IF;

    SELECT *
      INTO v_order
      FROM app.sales_order
     WHERE order_id = p_order_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Order not found or not visible'
            USING ERRCODE = 'P0002';
    END IF;

    IF v_order.tenant_id <> app.current_tenant_id() THEN
        RAISE EXCEPTION 'Tenant context does not match the order'
            USING ERRCODE = '42501';
    END IF;

    IF v_order.order_status = 'cancelled' THEN
        RETURN;
    END IF;

    IF v_order.order_status = 'fulfilled' THEN
        RAISE EXCEPTION 'Fulfilled orders cannot be cancelled'
            USING ERRCODE = 'P0001';
    END IF;

    FOR v_reservation IN
        SELECT
            order_id,
            line_no,
            warehouse_id,
            product_id,
            quantity
        FROM app.order_reservation
        WHERE order_id = p_order_id
          AND reservation_state = 'reserved'
        ORDER BY product_id, warehouse_id, line_no
        FOR UPDATE
    LOOP
        UPDATE app.inventory
           SET reserved = reserved - v_reservation.quantity,
               updated_at = clock_timestamp()
         WHERE warehouse_id = v_reservation.warehouse_id
           AND product_id = v_reservation.product_id
           AND reserved >= v_reservation.quantity;

        IF NOT FOUND THEN
            RAISE EXCEPTION
                'Cannot release reservation for product %',
                v_reservation.product_id
                USING ERRCODE = 'P0001';
        END IF;

        UPDATE app.order_reservation
           SET reservation_state = 'released'
         WHERE order_id = v_reservation.order_id
           AND line_no = v_reservation.line_no;
    END LOOP;

    UPDATE app.sales_order
       SET order_status = 'cancelled'
     WHERE order_id = p_order_id;
END;
$$;

