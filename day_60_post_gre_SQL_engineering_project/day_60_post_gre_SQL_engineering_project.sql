-- Application grants are conditional so this baseline can be installed
-- before the deployment team creates the app_runtime login role.
-- The runtime role must not own these schemas or tables.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM pg_roles
        WHERE rolname = 'app_runtime'
    ) THEN
        GRANT USAGE ON SCHEMA app TO app_runtime;

        GRANT SELECT ON
            app.tenant,
            app.customer,
            app.product,
            app.warehouse,
            app.inventory,
            app.sales_order,
            app.order_item,
            app.order_reservation
        TO app_runtime;

        GRANT INSERT ON
            app.sales_order,
            app.order_item
        TO app_runtime;

        GRANT UPDATE, DELETE ON app.order_item TO app_runtime;

        GRANT USAGE, SELECT
        ON ALL SEQUENCES IN SCHEMA app
        TO app_runtime;

        GRANT EXECUTE
        ON FUNCTION app.current_tenant_id()
        TO app_runtime;

        GRANT EXECUTE
        ON FUNCTION app.reserve_order(bigint, bigint)
        TO app_runtime;

        GRANT EXECUTE
        ON FUNCTION app.fulfill_order(bigint)
        TO app_runtime;

        GRANT EXECUTE
        ON FUNCTION app.cancel_order(bigint)
        TO app_runtime;
    END IF;
END;
$$;

