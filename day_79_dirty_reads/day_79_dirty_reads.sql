/* ============================================================
   4. AUDIT TRIGGER
   ============================================================ */

CREATE OR REPLACE FUNCTION audit_balance_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.balance IS DISTINCT FROM OLD.balance THEN

        INSERT INTO transaction_audit (
            transaction_reference,
            account_id,
            operation,
            old_balance,
            new_balance,
            database_transaction_id
        )
        VALUES (
            'ACCOUNT-' || NEW.account_id,
            NEW.account_id,
            'BALANCE_UPDATE',
            OLD.balance,
            NEW.balance,
            txid_current()
        );

    END IF;

    RETURN NEW;
END;
$$;


DROP TRIGGER IF EXISTS trg_audit_balance_change
ON accounts;

CREATE TRIGGER trg_audit_balance_change
AFTER UPDATE OF balance ON accounts
FOR EACH ROW
EXECUTE FUNCTION audit_balance_change();


/* ============================================================
   5. SAFE BALANCE UPDATE FUNCTION
   ============================================================ */

CREATE OR REPLACE FUNCTION update_account_balance(
    p_account_id BIGINT,
    p_new_balance NUMERIC(15, 2)
)
RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
DECLARE
    v_status VARCHAR(20);
BEGIN
    IF p_new_balance IS NULL OR p_new_balance < 0 THEN
        RAISE EXCEPTION
            'Balance must be a non-negative value.';
    END IF;

    SELECT account_status
    INTO v_status
    FROM accounts
    WHERE account_id = p_account_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Account % does not exist.', p_account_id;
    END IF;

    IF v_status <> 'ACTIVE' THEN
        RAISE EXCEPTION
            'Account % is not active.', p_account_id;
    END IF;

    UPDATE accounts
    SET balance = p_new_balance
    WHERE account_id = p_account_id;

    RETURN TRUE;
END;
$$;


/* ============================================================
   6. SAFE TRANSFER PROCEDURE
   ============================================================ */

CREATE OR REPLACE PROCEDURE transfer_funds(
    p_source BIGINT,
    p_destination BIGINT,
    p_amount NUMERIC(15, 2)
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_source_balance NUMERIC(15, 2);
    v_destination_balance NUMERIC(15, 2);
    v_source_status VARCHAR(20);
    v_destination_status VARCHAR(20);
BEGIN
    IF p_source = p_destination THEN
        RAISE EXCEPTION
            'Source and destination must differ.';
    END IF;

    IF p_amount IS NULL OR p_amount <= 0 THEN
        RAISE EXCEPTION
            'Transfer amount must be positive.';
    END IF;

    /*
       Lock records in a consistent order to reduce
       deadlock risk when two transfers involve the same accounts.
    */
    PERFORM account_id
    FROM accounts
    WHERE account_id IN (p_source, p_destination)
    ORDER BY account_id
    FOR UPDATE;

    SELECT balance, account_status
    INTO v_source_balance, v_source_status
    FROM accounts
    WHERE account_id = p_source;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Source account does not exist.';
    END IF;

    SELECT balance, account_status
    INTO v_destination_balance, v_destination_status
    FROM accounts
    WHERE account_id = p_destination;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Destination account does not exist.';
    END IF;

    IF v_source_status <> 'ACTIVE'
       OR v_destination_status <> 'ACTIVE' THEN
        RAISE EXCEPTION
            'Both accounts must be active.';
    END IF;

    IF v_source_balance < p_amount THEN
        RAISE EXCEPTION 'Insufficient funds.';
    END IF;

    UPDATE accounts
    SET balance = balance - p_amount
    WHERE account_id = p_source;

    UPDATE accounts
    SET balance = balance + p_amount
    WHERE account_id = p_destination;

    /*
       The caller controls the transaction boundary.
       Both changes commit or roll back together.
    */
END;
$$;


/* ============================================================
   7. ISOLATION CAPABILITY REPORT
   ============================================================ */

CREATE OR REPLACE VIEW isolation_capability_report AS
SELECT
    'READ UNCOMMITTED'::VARCHAR AS requested_isolation,
    'READ COMMITTED'::VARCHAR AS effective_postgresql_isolation,
    FALSE AS dirty_reads_allowed,
    'PostgreSQL maps READ UNCOMMITTED to READ COMMITTED.'
        AS explanation

UNION ALL

SELECT
    'READ COMMITTED',
    'READ COMMITTED',
    FALSE,
    'Each statement sees a committed snapshot at statement start.'

UNION ALL

SELECT
    'REPEATABLE READ',
    'REPEATABLE READ',
    FALSE,
    'Transaction-level snapshot prevents non-repeatable reads.';


/* ============================================================
   8. TRANSACTION OBSERVATION FUNCTION
   ============================================================ */

CREATE OR REPLACE FUNCTION get_transaction_observation(
    p_account_id BIGINT
)
RETURNS TABLE (
    account_id BIGINT,
    visible_balance NUMERIC(15, 2),
    effective_isolation TEXT,
    transaction_identifier TEXT
)
LANGUAGE SQL
STABLE
AS $$
    SELECT
        a.account_id,
        a.balance,
        current_setting('transaction_isolation'),
        txid_current()::TEXT
    FROM accounts a
    WHERE a.account_id = p_account_id;
$$;


