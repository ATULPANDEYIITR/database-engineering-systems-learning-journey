/* ============================================================
   16. WORKFLOW PROCESSING
   ============================================================ */

CREATE OR REPLACE FUNCTION evaluate_transaction_safety(
    p_isolation TEXT
)
RETURNS TABLE (
    isolation_level TEXT,
    dirty_read_protection BOOLEAN,
    recommendation TEXT
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_isolation NOT IN (
        'read uncommitted',
        'read committed',
        'repeatable read',
        'serializable'
    ) THEN
        RAISE EXCEPTION
            'Unsupported isolation level: %', p_isolation;
    END IF;

    RETURN QUERY
    SELECT
        p_isolation,
        TRUE,
        CASE p_isolation
            WHEN 'read uncommitted' THEN
                'PostgreSQL uses READ COMMITTED behavior.'
            WHEN 'read committed' THEN
                'Suitable when statement-level committed visibility is sufficient.'
            WHEN 'repeatable read' THEN
                'Suitable when a stable transaction snapshot is required.'
            WHEN 'serializable' THEN
                'Use for transactions requiring serializable execution; handle retries.'
        END::TEXT;
END;
$$;


SELECT *
FROM evaluate_transaction_safety('read committed');


/* ============================================================
   17. CONCURRENT SESSION EXPERIMENT
   ============================================================ */

/*
    The following experiment MUST be executed using two
    independent PostgreSQL connections.

    CONNECTION A
    ------------

    BEGIN;
    SET TRANSACTION ISOLATION LEVEL READ COMMITTED;

    UPDATE dirty_read_lab.accounts
    SET balance = 100.00
    WHERE account_id = 101;

    SELECT balance
    FROM dirty_read_lab.accounts
    WHERE account_id = 101;

    -- Do not commit yet.


    CONNECTION B
    ------------

    BEGIN;
    SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;

    SELECT
        balance,
        current_setting('transaction_isolation')
    FROM dirty_read_lab.accounts
    WHERE account_id = 101;

    Expected result:
    - Connection B sees the previous committed balance.
    - It does not see the uncommitted value 100.00.
    - PostgreSQL reports READ COMMITTED as the effective
      isolation behavior.

    Return to CONNECTION A:

    ROLLBACK;

    Connection B can continue reading the committed balance.

    The same experiment can be performed with
    READ COMMITTED and REPEATABLE READ in Connection B.

    For a real dirty-read experiment, use a database engine
    that supports READ UNCOMMITTED visibility.
*/


/* ============================================================
   18. SECURITY AND OPERATIONAL NOTES
   ============================================================ */

/*
    Production controls:

    1. Use least-privilege database roles.
    2. Avoid exposing uncommitted business data.
    3. Use parameterized queries.
    4. Validate monetary values and transaction boundaries.
    5. Use row locking for critical read-modify-write operations.
    6. Handle deadlocks and serialization failures with retries.
    7. Restrict audit-table modification privileges.
    8. Monitor long-running transactions.
    9. Keep transactions short.
   10. Do not assume that READ UNCOMMITTED behaves identically
       across database products.

    PostgreSQL-specific distinction:

    READ UNCOMMITTED and READ COMMITTED have the same effective
    behavior in PostgreSQL. This is different from database
    systems that implement dirty-read visibility.
*/


