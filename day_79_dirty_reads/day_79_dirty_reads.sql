/*
    DIRTY READS: CAUSES, EXAMPLES AND PREVENTION
    PostgreSQL 14+

    This script creates an executable transaction-isolation laboratory.

    It covers:
    - Transaction write visibility.
    - Dirty-read prevention.
    - READ UNCOMMITTED behavior in PostgreSQL.
    - READ COMMITTED.
    - REPEATABLE READ.
    - Transaction rollback.
    - Account integrity.
    - Audit logging.
    - Isolation-level reporting.
    - Concurrent-session demonstrations.

    IMPORTANT:

    PostgreSQL treats READ UNCOMMITTED as READ COMMITTED.
    Therefore, PostgreSQL does not permit dirty reads.

    The separate-session examples at the end require two
    PostgreSQL connections to demonstrate concurrency.
*/

BEGIN;

CREATE SCHEMA IF NOT EXISTS dirty_read_lab;

SET search_path TO dirty_read_lab, public;


/* ============================================================
   1. DOMAIN TABLES
   ============================================================ */

CREATE TABLE IF NOT EXISTS accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_name VARCHAR(120) NOT NULL,
    balance NUMERIC(15, 2) NOT NULL,
    account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT accounts_owner_nonempty
        CHECK (length(trim(owner_name)) > 0),

    CONSTRAINT accounts_balance_nonnegative
        CHECK (balance >= 0),

    CONSTRAINT accounts_status_valid
        CHECK (
            account_status IN (
                'ACTIVE',
                'SUSPENDED',
                'CLOSED'
            )
        )
);


CREATE TABLE IF NOT EXISTS transaction_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_reference VARCHAR(100) NOT NULL,
    account_id BIGINT NOT NULL REFERENCES accounts(account_id),
    operation VARCHAR(30) NOT NULL,
    old_balance NUMERIC(15, 2),
    new_balance NUMERIC(15, 2),
    database_transaction_id BIGINT NOT NULL DEFAULT txid_current(),
    executed_by TEXT NOT NULL DEFAULT CURRENT_USER,
    executed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT audit_operation_valid
        CHECK (
            operation IN (
                'BALANCE_UPDATE',
                'ACCOUNT_CREATION'
            )
        )
);


CREATE TABLE IF NOT EXISTS isolation_test_results (
    result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_name VARCHAR(100) NOT NULL,
    requested_isolation VARCHAR(30) NOT NULL,
    actual_isolation VARCHAR(30) NOT NULL,
    dirty_read_possible BOOLEAN NOT NULL,
    observation TEXT NOT NULL,
    tested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


