CREATE OR REPLACE VIEW latest_review_decisions AS
SELECT DISTINCT ON (r.pull_request_id, r.reviewer_id)
       r.pull_request_id,
       r.reviewer_id,
       r.decision,
       r.commit_sha,
       r.submitted_at,
       r.dismissed_at
FROM pull_request_reviews r
ORDER BY r.pull_request_id, r.reviewer_id, r.submitted_at DESC, r.review_id DESC;

CREATE OR REPLACE VIEW merge_eligibility AS
WITH current_policy AS (
    SELECT pr.pull_request_id,
           pr.repository_id,
           pr.target_branch,
           pr.state,
           pr.base_sha,
           pr.head_sha,
           pr.author_id,
           p.policy_id,
           p.required_approvals,
           p.require_conversation_resolution,
           p.require_up_to_date_branch,
           p.require_linear_history,
           p.dismiss_stale_approvals
    FROM pull_requests pr
    LEFT JOIN branch_protection_policies p
      ON p.repository_id = pr.repository_id
     AND p.branch_name = pr.target_branch
     AND p.enabled
),
eligible_approvals AS (
    SELECT cp.pull_request_id,
           COUNT(DISTINCT lr.reviewer_id) AS approval_count
    FROM current_policy cp
    LEFT JOIN latest_review_decisions lr
      ON lr.pull_request_id = cp.pull_request_id
     AND lr.decision = 'approved'
     AND lr.dismissed_at IS NULL
     AND (NOT cp.dismiss_stale_approvals OR lr.commit_sha = cp.head_sha)
    LEFT JOIN reviewers rv
      ON rv.reviewer_id = lr.reviewer_id
     AND rv.active
    WHERE rv.reviewer_id IS NOT NULL
      AND (
          cp.policy_id IS NULL
          OR NOT EXISTS (
              SELECT 1 FROM policy_approver_teams pat
              WHERE pat.policy_id = cp.policy_id
          )
          OR EXISTS (
              SELECT 1
              FROM policy_approver_teams pat
              JOIN reviewer_teams rt ON rt.team_name = pat.team_name
              WHERE pat.policy_id = cp.policy_id
                AND rt.reviewer_id = lr.reviewer_id
          )
      )
    GROUP BY cp.pull_request_id
),
required_check_results AS (
    SELECT cp.pull_request_id,
           COUNT(*) FILTER (
               WHERE latest_check.status = 'success'
                 AND latest_check.commit_sha = cp.head_sha
           ) AS passing_required_checks,
           COUNT(prc.check_context) AS total_required_checks
    FROM current_policy cp
    LEFT JOIN policy_required_checks prc ON prc.policy_id = cp.policy_id
    LEFT JOIN LATERAL (
        SELECT sc.status, sc.commit_sha
        FROM status_checks sc
        WHERE sc.pull_request_id = cp.pull_request_id
          AND sc.check_context = prc.check_context
        ORDER BY sc.started_at DESC, sc.status_check_id DESC
        LIMIT 1
    ) latest_check ON TRUE
    GROUP BY cp.pull_request_id
),
unresolved_comments AS (
    SELECT r.pull_request_id, COUNT(*) AS unresolved_count
    FROM pull_request_reviews r
    JOIN review_comments c ON c.review_id = r.review_id
    WHERE NOT c.resolved
    GROUP BY r.pull_request_id
)
SELECT cp.pull_request_id,
       cp.repository_id,
       cp.state,
       COALESCE(ea.approval_count, 0) AS eligible_approvals,
       COALESCE(cp.required_approvals, 0) AS required_approvals,
       COALESCE(cr.passing_required_checks, 0) AS passing_required_checks,
       COALESCE(cr.total_required_checks, 0) AS total_required_checks,
       COALESCE(uc.unresolved_count, 0) AS unresolved_comments,
       CASE
           WHEN cp.state <> 'open' THEN FALSE
           WHEN cp.policy_id IS NULL THEN TRUE
           WHEN COALESCE(ea.approval_count, 0) < cp.required_approvals THEN FALSE
           WHEN COALESCE(cr.passing_required_checks, 0)
                < COALESCE(cr.total_required_checks, 0) THEN FALSE
           WHEN cp.require_conversation_resolution
                AND COALESCE(uc.unresolved_count, 0) > 0 THEN FALSE
           WHEN cp.require_up_to_date_branch
                AND cp.base_sha <> target.head_sha THEN FALSE
           ELSE TRUE
       END AS policy_eligible
FROM current_policy cp
JOIN branches target
  ON target.repository_id = cp.repository_id
 AND target.branch_name = cp.target_branch
LEFT JOIN eligible_approvals ea ON ea.pull_request_id = cp.pull_request_id
LEFT JOIN required_check_results cr ON cr.pull_request_id = cp.pull_request_id
LEFT JOIN unresolved_comments uc ON uc.pull_request_id = cp.pull_request_id;

CREATE OR REPLACE FUNCTION merge_pull_request(
    p_pull_request_id BIGINT,
    p_actor_id TEXT,
    p_strategy TEXT
)
RETURNS TEXT
LANGUAGE plpgsql
SET search_path = repo_governance, public
AS $$
DECLARE
    v_pr pull_requests%ROWTYPE;
    v_target branches%ROWTYPE;
    v_source branches%ROWTYPE;
    v_repository repositories%ROWTYPE;
    v_policy branch_protection_policies%ROWTYPE;
    v_eligible BOOLEAN;
    v_merge_sha TEXT;
    v_detail JSONB;
BEGIN
    IF btrim(COALESCE(p_actor_id, '')) = '' THEN
        RAISE EXCEPTION 'Merge actor is required';
    END IF;
    IF p_strategy NOT IN ('merge_commit', 'squash', 'rebase') THEN
        RAISE EXCEPTION 'Unsupported merge strategy: %', p_strategy;
    END IF;

    -- Lock the request and target branch to prevent concurrent merge decisions
    -- from observing different versions of the same branch head.
    SELECT * INTO v_pr
    FROM pull_requests
    WHERE pull_request_id = p_pull_request_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Pull request % does not exist', p_pull_request_id;
    END IF;
    IF v_pr.state <> 'open' THEN
        RAISE EXCEPTION 'Only open pull requests can be merged';
    END IF;

    SELECT * INTO v_repository
    FROM repositories
    WHERE repository_id = v_pr.repository_id
    FOR UPDATE;

    IF v_repository.archived THEN
        RAISE EXCEPTION 'Archived repositories cannot be merged into';
    END IF;

    SELECT * INTO v_source
    FROM branches
    WHERE repository_id = v_pr.repository_id
      AND branch_name = v_pr.source_branch
    FOR UPDATE;

    SELECT * INTO v_target
    FROM branches
    WHERE repository_id = v_pr.repository_id
      AND branch_name = v_pr.target_branch
    FOR UPDATE;

    IF v_source.is_deleted OR v_target.is_deleted THEN
        RAISE EXCEPTION 'Source and target branches must be active';
    END IF;
    IF v_source.head_sha <> v_pr.head_sha THEN
        RAISE EXCEPTION 'Pull request head differs from source branch head';
    END IF;

    SELECT * INTO v_policy
    FROM branch_protection_policies
    WHERE repository_id = v_pr.repository_id
      AND branch_name = v_pr.target_branch
      AND enabled
    FOR UPDATE;

    IF FOUND THEN
        IF NOT EXISTS (
            SELECT 1 FROM policy_merge_strategies pms
            WHERE pms.policy_id = v_policy.policy_id
              AND pms.merge_strategy = p_strategy
        ) THEN
            RAISE EXCEPTION 'Merge strategy % is not permitted', p_strategy;
        END IF;

        IF v_policy.require_up_to_date_branch AND v_pr.base_sha <> v_target.head_sha THEN
            RAISE EXCEPTION 'Target branch advanced; synchronize the pull request base';
        END IF;

        IF v_policy.require_linear_history AND p_strategy = 'merge_commit' THEN
            RAISE EXCEPTION 'Merge commit violates linear-history policy';
        END IF;

        SELECT policy_eligible INTO v_eligible
        FROM merge_eligibility
        WHERE pull_request_id = p_pull_request_id;

        IF v_eligible IS DISTINCT FROM TRUE THEN
            RAISE EXCEPTION 'Pull request fails merge eligibility policy';
        END IF;

        IF v_policy.require_signed_commits AND EXISTS (
            SELECT 1
            FROM pull_request_commits pc
            JOIN commits c
              ON c.repository_id = pc.repository_id
             AND c.commit_sha = pc.commit_sha
            WHERE pc.pull_request_id = p_pull_request_id
              AND NOT c.signature_verified
        ) THEN
            RAISE EXCEPTION 'One or more pull request commits are not verified as signed';
        END IF;
    END IF;

    -- The database records the workflow transition. Actual Git tree construction
    -- and cryptographic SHA computation belong to the trusted Git service.
    v_merge_sha := 'db-merge-' || v_pr.pull_request_number || '-' ||
                   substring(v_pr.head_sha FROM 1 FOR 16);

    INSERT INTO commits (
        repository_id, commit_sha, author_id, commit_message, signature_verified
    ) VALUES (
        v_pr.repository_id,
        v_merge_sha,
        p_actor_id,
        'Merge pull request #' || v_pr.pull_request_number || ': ' || v_pr.title,
        FALSE
    );

    INSERT INTO commit_parents(repository_id, commit_sha, parent_sha, parent_position)
    VALUES
        (v_pr.repository_id, v_merge_sha, v_target.head_sha, 1),
        (v_pr.repository_id, v_merge_sha, v_pr.head_sha, 2);

    UPDATE branches
    SET head_sha = v_merge_sha
    WHERE branch_id = v_target.branch_id;

    UPDATE pull_requests
    SET state = 'merged',
        merged_sha = v_merge_sha,
        merge_strategy = p_strategy,
        merged_at = clock_timestamp()
    WHERE pull_request_id = p_pull_request_id;

    v_detail := jsonb_build_object(
        'strategy', p_strategy,
        'previous_base', v_target.head_sha,
        'head_sha', v_pr.head_sha,
        'merge_sha', v_merge_sha
    );

    INSERT INTO merge_audit (
        repository_id, pull_request_id, actor_id, action, details
    ) VALUES (
        v_pr.repository_id, p_pull_request_id, p_actor_id, 'merged', v_detail
    );

    RETURN v_merge_sha;
END;
$$;

