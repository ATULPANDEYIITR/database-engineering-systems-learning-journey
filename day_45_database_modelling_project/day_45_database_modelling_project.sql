CREATE OR REPLACE FUNCTION enforce_branch_head_repository()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = repo_governance, public
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM commits c
        WHERE c.repository_id = NEW.repository_id
          AND c.commit_sha = NEW.head_sha
    ) THEN
        RAISE EXCEPTION 'Branch head must belong to the same repository';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_branch_head_integrity ON branches;
CREATE TRIGGER trg_branch_head_integrity
BEFORE INSERT OR UPDATE OF repository_id, head_sha ON branches
FOR EACH ROW EXECUTE FUNCTION enforce_branch_head_repository();

CREATE OR REPLACE FUNCTION enforce_pull_request_author()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = repo_governance, public
AS $$
BEGIN
    IF NEW.author_id IS NULL OR btrim(NEW.author_id) = '' THEN
        RAISE EXCEPTION 'Pull request author is required';
    END IF;
    IF NEW.source_branch = NEW.target_branch THEN
        RAISE EXCEPTION 'Pull request source and target must differ';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM repositories r
        WHERE r.repository_id = NEW.repository_id AND NOT r.archived
    ) AND TG_OP = 'INSERT' THEN
        RAISE EXCEPTION 'Cannot open a pull request in an archived repository';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_pull_request_integrity ON pull_requests;
CREATE TRIGGER trg_pull_request_integrity
BEFORE INSERT OR UPDATE OF author_id, source_branch, target_branch, repository_id
ON pull_requests
FOR EACH ROW EXECUTE FUNCTION enforce_pull_request_author();

CREATE OR REPLACE FUNCTION enforce_review_eligibility()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = repo_governance, public
AS $$
DECLARE
    v_author TEXT;
    v_active BOOLEAN;
BEGIN
    SELECT author_id INTO v_author
    FROM pull_requests
    WHERE pull_request_id = NEW.pull_request_id;

    SELECT active INTO v_active
    FROM reviewers
    WHERE reviewer_id = NEW.reviewer_id;

    IF v_active IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION 'Reviewer must exist and be active';
    END IF;
    IF NEW.decision = 'approved' AND NEW.reviewer_id = v_author THEN
        RAISE EXCEPTION 'Pull request author cannot approve their own changes';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_review_eligibility ON pull_request_reviews;
CREATE TRIGGER trg_review_eligibility
BEFORE INSERT OR UPDATE OF reviewer_id, decision, pull_request_id
ON pull_request_reviews
FOR EACH ROW EXECUTE FUNCTION enforce_review_eligibility();

CREATE OR REPLACE FUNCTION enforce_commit_repository()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = repo_governance, public
AS $$
DECLARE
    v_repository_id BIGINT;
BEGIN
    SELECT repository_id INTO v_repository_id
    FROM pull_requests
    WHERE pull_request_id = NEW.pull_request_id;

    IF NOT EXISTS (
        SELECT 1 FROM commits c
        WHERE c.repository_id = v_repository_id
          AND c.commit_sha = NEW.commit_sha
    ) THEN
        RAISE EXCEPTION 'Evidence commit must belong to the pull request repository';
    END IF;
    RETURN NEW;
END;
$$;

