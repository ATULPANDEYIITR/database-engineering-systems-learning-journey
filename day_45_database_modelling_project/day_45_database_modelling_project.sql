/*
 * PostgreSQL 15+ relational modeling project.
 *
 * The schema separates repository topology, pull request lifecycle, immutable
 * commit references, review decisions, inline discussions, CI evidence, and
 * branch-protection policy. Foreign keys and unique constraints enforce
 * identity and ownership. A transactional merge function checks current
 * policy and records the resulting state change.
 *
 * Execute in a dedicated development database. The schema is intentionally
 * created under its own namespace and the script is repeatable.
 */

BEGIN;

CREATE SCHEMA IF NOT EXISTS repo_governance;
SET LOCAL search_path TO repo_governance, public;

CREATE TABLE IF NOT EXISTS repositories (
    repository_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_name          TEXT NOT NULL CHECK (btrim(owner_name) <> ''),
    repository_name     TEXT NOT NULL CHECK (btrim(repository_name) <> ''),
    default_branch_name TEXT NOT NULL CHECK (btrim(default_branch_name) <> ''),
    archived            BOOLEAN NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_repository_owner_name UNIQUE (owner_name, repository_name)
);

CREATE TABLE IF NOT EXISTS repository_members (
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id) ON DELETE RESTRICT,
    user_id       TEXT NOT NULL CHECK (btrim(user_id) <> ''),
    role_name     TEXT NOT NULL CHECK (
        role_name IN ('read', 'triage', 'write', 'maintain', 'admin')
    ),
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    joined_at     TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (repository_id, user_id)
);

CREATE TABLE IF NOT EXISTS branches (
    branch_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id  BIGINT NOT NULL REFERENCES repositories(repository_id) ON DELETE RESTRICT,
    branch_name    TEXT NOT NULL CHECK (btrim(branch_name) <> ''),
    head_sha       TEXT NOT NULL CHECK (btrim(head_sha) <> ''),
    is_deleted     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_branch_name_per_repository UNIQUE (repository_id, branch_name),
    CONSTRAINT uq_branch_id_repository UNIQUE (branch_id, repository_id)
);

CREATE TABLE IF NOT EXISTS commits (
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id) ON DELETE RESTRICT,
    commit_sha    TEXT NOT NULL CHECK (btrim(commit_sha) <> ''),
    author_id     TEXT NOT NULL CHECK (btrim(author_id) <> ''),
    commit_message TEXT NOT NULL CHECK (btrim(commit_message) <> ''),
    committed_at  TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    signature_verified BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (repository_id, commit_sha)
);

CREATE TABLE IF NOT EXISTS commit_parents (
    repository_id BIGINT NOT NULL,
    commit_sha    TEXT NOT NULL,
    parent_sha    TEXT NOT NULL,
    parent_position SMALLINT NOT NULL CHECK (parent_position >= 1),
    PRIMARY KEY (repository_id, commit_sha, parent_sha),
    UNIQUE (repository_id, commit_sha, parent_position),
    FOREIGN KEY (repository_id, commit_sha)
        REFERENCES commits(repository_id, commit_sha) ON DELETE RESTRICT,
    FOREIGN KEY (repository_id, parent_sha)
        REFERENCES commits(repository_id, commit_sha) ON DELETE RESTRICT,
    CHECK (commit_sha <> parent_sha)
);

ALTER TABLE branches
    ADD CONSTRAINT fk_branch_head_commit
    FOREIGN KEY (repository_id, head_sha)
    REFERENCES commits(repository_id, commit_sha)
    DEFERRABLE INITIALLY DEFERRED;

ALTER TABLE repositories
    ADD CONSTRAINT fk_repository_default_branch
    FOREIGN KEY (repository_id, default_branch_name)
    REFERENCES branches(repository_id, branch_name)
    DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE IF NOT EXISTS pull_requests (
    pull_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id   BIGINT NOT NULL REFERENCES repositories(repository_id) ON DELETE RESTRICT,
    pull_request_number INTEGER NOT NULL CHECK (pull_request_number > 0),
    author_id       TEXT NOT NULL CHECK (btrim(author_id) <> ''),
    source_branch   TEXT NOT NULL,
    target_branch   TEXT NOT NULL,
    title           TEXT NOT NULL CHECK (btrim(title) <> ''),
    description     TEXT NOT NULL DEFAULT '',
    state           TEXT NOT NULL DEFAULT 'open'
                    CHECK (state IN ('draft', 'open', 'closed', 'merged')),
    base_sha        TEXT NOT NULL,
    head_sha        TEXT NOT NULL,
    merged_sha      TEXT,
    merge_strategy  TEXT CHECK (
        merge_strategy IS NULL OR
        merge_strategy IN ('merge_commit', 'squash', 'rebase')
    ),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    closed_at       TIMESTAMPTZ,
    merged_at       TIMESTAMPTZ,
    CONSTRAINT uq_pr_number_per_repository UNIQUE (repository_id, pull_request_number),
    CONSTRAINT ck_pr_distinct_branches CHECK (source_branch <> target_branch),
    CONSTRAINT ck_pr_merge_metadata CHECK (
        (state = 'merged' AND merged_sha IS NOT NULL
            AND merge_strategy IS NOT NULL AND merged_at IS NOT NULL)
        OR
        (state <> 'merged' AND merged_sha IS NULL
            AND merge_strategy IS NULL AND merged_at IS NULL)
    ),
    FOREIGN KEY (repository_id, source_branch)
        REFERENCES branches(repository_id, branch_name) ON DELETE RESTRICT,
    FOREIGN KEY (repository_id, target_branch)
        REFERENCES branches(repository_id, branch_name) ON DELETE RESTRICT,
    FOREIGN KEY (repository_id, base_sha)
        REFERENCES commits(repository_id, commit_sha) ON DELETE RESTRICT,
    FOREIGN KEY (repository_id, head_sha)
        REFERENCES commits(repository_id, commit_sha) ON DELETE RESTRICT,
    FOREIGN KEY (repository_id, merged_sha)
        REFERENCES commits(repository_id, commit_sha) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS pull_request_commits (
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id) ON DELETE RESTRICT,
    repository_id   BIGINT NOT NULL,
    commit_sha      TEXT NOT NULL,
    position        INTEGER NOT NULL CHECK (position >= 1),
    PRIMARY KEY (pull_request_id, commit_sha),
    UNIQUE (pull_request_id, position),
    FOREIGN KEY (repository_id, commit_sha)
        REFERENCES commits(repository_id, commit_sha) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS branch_protection_policies (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL,
    branch_name TEXT NOT NULL,
    required_approvals INTEGER NOT NULL DEFAULT 1 CHECK (required_approvals >= 0),
    require_code_owner_review BOOLEAN NOT NULL DEFAULT FALSE,
    require_conversation_resolution BOOLEAN NOT NULL DEFAULT TRUE,
    require_linear_history BOOLEAN NOT NULL DEFAULT FALSE,
    require_signed_commits BOOLEAN NOT NULL DEFAULT FALSE,
    require_up_to_date_branch BOOLEAN NOT NULL DEFAULT TRUE,
    dismiss_stale_approvals BOOLEAN NOT NULL DEFAULT TRUE,
    restrict_direct_pushes BOOLEAN NOT NULL DEFAULT TRUE,
    prohibit_force_pushes BOOLEAN NOT NULL DEFAULT TRUE,
    prohibit_deletion BOOLEAN NOT NULL DEFAULT TRUE,
    allow_administrator_bypass BOOLEAN NOT NULL DEFAULT FALSE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_protection_policy_branch UNIQUE (repository_id, branch_name),
    FOREIGN KEY (repository_id, branch_name)
        REFERENCES branches(repository_id, branch_name) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS policy_required_checks (
    policy_id BIGINT NOT NULL REFERENCES branch_protection_policies(policy_id) ON DELETE RESTRICT,
    check_context TEXT NOT NULL CHECK (btrim(check_context) <> ''),
    PRIMARY KEY (policy_id, check_context)
);

CREATE TABLE IF NOT EXISTS policy_approver_teams (
    policy_id BIGINT NOT NULL REFERENCES branch_protection_policies(policy_id) ON DELETE RESTRICT,
    team_name TEXT NOT NULL CHECK (btrim(team_name) <> ''),
    PRIMARY KEY (policy_id, team_name)
);

CREATE TABLE IF NOT EXISTS policy_merge_strategies (
    policy_id BIGINT NOT NULL REFERENCES branch_protection_policies(policy_id) ON DELETE RESTRICT,
    merge_strategy TEXT NOT NULL CHECK (
        merge_strategy IN ('merge_commit', 'squash', 'rebase')
    ),
    PRIMARY KEY (policy_id, merge_strategy)
);

CREATE TABLE IF NOT EXISTS reviewers (
    reviewer_id TEXT PRIMARY KEY CHECK (btrim(reviewer_id) <> ''),
    display_name TEXT NOT NULL CHECK (btrim(display_name) <> ''),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS reviewer_teams (
    reviewer_id TEXT NOT NULL REFERENCES reviewers(reviewer_id) ON DELETE RESTRICT,
    team_name TEXT NOT NULL CHECK (btrim(team_name) <> ''),
    PRIMARY KEY (reviewer_id, team_name)
);

CREATE TABLE IF NOT EXISTS pull_request_reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id) ON DELETE RESTRICT,
    reviewer_id TEXT NOT NULL REFERENCES reviewers(reviewer_id) ON DELETE RESTRICT,
    commit_sha TEXT NOT NULL,
    decision TEXT NOT NULL CHECK (
        decision IN ('comment', 'approved', 'changes_requested', 'dismissed')
    ),
    review_body TEXT NOT NULL DEFAULT '',
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    dismissed_at TIMESTAMPTZ,
    dismissed_by TEXT,
    FOREIGN KEY (pull_request_id, commit_sha)
        REFERENCES pull_requests(pull_request_id, head_sha)
        DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS review_comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL REFERENCES pull_request_reviews(review_id) ON DELETE RESTRICT,
    body TEXT NOT NULL CHECK (btrim(body) <> ''),
    file_path TEXT,
    line_number INTEGER,
    resolved BOOLEAN NOT NULL DEFAULT FALSE,
    resolved_by TEXT,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_inline_comment_location CHECK (
        (file_path IS NULL AND line_number IS NULL)
        OR
        (file_path IS NOT NULL AND btrim(file_path) <> '' AND line_number >= 1)
    ),
    CONSTRAINT ck_resolution_metadata CHECK (
        (resolved = FALSE AND resolved_at IS NULL)
        OR
        (resolved = TRUE AND resolved_at IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS status_checks (
    status_check_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id) ON DELETE RESTRICT,
    check_context TEXT NOT NULL CHECK (btrim(check_context) <> ''),
    commit_sha TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('pending', 'success', 'failure', 'error', 'skipped')),
    external_run_id TEXT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    completed_at TIMESTAMPTZ,
    CONSTRAINT ck_check_completion CHECK (
        (status = 'pending' AND completed_at IS NULL)
        OR
        (status <> 'pending' AND completed_at IS NOT NULL)
    ),
    UNIQUE (pull_request_id, check_context, commit_sha, external_run_id)
);

CREATE TABLE IF NOT EXISTS merge_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL REFERENCES repositories(repository_id) ON DELETE RESTRICT,
    pull_request_id BIGINT NOT NULL REFERENCES pull_requests(pull_request_id) ON DELETE RESTRICT,
    actor_id TEXT NOT NULL CHECK (btrim(actor_id) <> ''),
    action TEXT NOT NULL CHECK (
        action IN ('opened', 'published', 'review_submitted', 'synchronized',
                   'closed', 'reopened', 'merged', 'merge_rejected',
                   'direct_push_rejected', 'force_push_rejected')
    ),
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX IF NOT EXISTS ix_pr_repository_state_created
    ON pull_requests(repository_id, state, created_at DESC);

