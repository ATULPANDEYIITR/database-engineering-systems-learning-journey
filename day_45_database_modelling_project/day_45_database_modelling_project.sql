-- Transactional merge demonstration. Run after inspecting merge_eligibility.
-- The seeded request is blocked by linear-history policy only if merge_commit
-- is selected; squash is permitted by the seeded policy.
DO $$
DECLARE
    v_pr_id BIGINT;
    v_merge_sha TEXT;
BEGIN
    SELECT pull_request_id INTO v_pr_id
    FROM pull_requests
    WHERE pull_request_number = 41
      AND repository_id = (
          SELECT repository_id FROM repositories
          WHERE owner_name = 'platform-team'
            AND repository_name = 'payments-api'
      );

    IF v_pr_id IS NOT NULL THEN
        -- The function performs its own eligibility checks and row locking.
        -- The exception block rolls back the attempted merge subtransaction.
        BEGIN
            v_merge_sha := merge_pull_request(v_pr_id, 'release-bot', 'squash');
            RAISE NOTICE 'Merge completed: %', v_merge_sha;
        EXCEPTION WHEN OTHERS THEN
            RAISE NOTICE 'Merge not completed: %', SQLERRM;
        END;
    END IF;
END;
$$;

